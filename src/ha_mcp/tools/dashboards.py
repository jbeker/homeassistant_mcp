"""Dashboard (Lovelace) tools over the WebSocket API.

Dashboards are only reachable through the ``lovelace/*`` WebSocket commands.
Reads register in every mode; mutations register only when ``admin`` is true.

Three levels of editing are offered:

- whole config: ``save_dashboard_config`` / ``delete_dashboard_config``
- one view: ``set_dashboard_view`` / ``delete_dashboard_view``
- one card: ``set_dashboard_card`` / ``delete_dashboard_card``

View and card tools perform a read-modify-write of the full stored config and
return the affected element after reading the saved config back.

``url_path=None`` addresses the default dashboard (Overview). A default
dashboard that has never been edited is auto-generated by the frontend and has
no stored config, so ``lovelace/config`` reports ``config_not_found`` for it;
``save_dashboard_config`` with a full config takes control of it.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

from ha_mcp.tools._annotations import mutation, read_only
from ha_mcp.ws_client import HAToolError

if TYPE_CHECKING:
    from mcp.server.fastmcp import FastMCP

    from ha_mcp.ws_client import HAWebSocketClient


_RESOURCE_TYPES = ("css", "js", "module", "html")


def register(mcp: FastMCP, ws: HAWebSocketClient, admin: bool) -> None:
    # -- reads ----------------------------------------------------------------

    @mcp.tool(annotations=read_only("List Dashboards"))
    async def list_dashboards() -> list[dict]:
        """List dashboards (storage- and YAML-mode).

        Each entry has id, url_path, title, icon, mode, require_admin, and
        show_in_sidebar. Content tools take url_path (e.g. 'garden-view');
        update_dashboard / delete_dashboard take id, a slug derived from it
        (e.g. 'garden_view'). The default dashboard (Overview) is not listed;
        address it with url_path=None in the content tools.
        """
        return await ws.ws_command("lovelace/dashboards/list")

    @mcp.tool(annotations=read_only("Get Dashboard Config"))
    async def get_dashboard_config(
        url_path: str | None = None, force: bool = False
    ) -> dict:
        """Get a dashboard's full config ({"views": [...], ...}).

        Fails with config_not_found if the dashboard does not exist or if the
        default dashboard has never been edited (it is then auto-generated and
        has no stored config; use save_dashboard_config to take control of it).

        Args:
            url_path: Dashboard url_path from list_dashboards, or None for the
                default dashboard.
            force: Bypass the server-side cache.
        """
        return await ws.ws_command("lovelace/config", url_path=url_path, force=force)

    @mcp.tool(annotations=read_only("List Dashboard Resources"))
    async def list_dashboard_resources() -> list[dict]:
        """List Lovelace resources (custom card JS modules and CSS)."""
        return await ws.ws_command("lovelace/resources")

    if not admin:
        return

    # -- dashboards -----------------------------------------------------------

    @mcp.tool(annotations=mutation("Create Dashboard"))
    async def create_dashboard(
        url_path: str,
        title: str,
        icon: str | None = None,
        require_admin: bool = False,
        show_in_sidebar: bool = True,
        allow_single_word: bool = False,
    ) -> dict:
        """Create an empty storage-mode dashboard. Returns it including id.

        Add content afterwards with save_dashboard_config or set_dashboard_view.

        Args:
            url_path: URL slug (e.g. 'garden-overview'). Must contain a hyphen
                unless allow_single_word is true.
            title: Sidebar title.
            icon: Optional MDI icon (e.g. 'mdi:flower').
            require_admin: Only admins can open it.
            show_in_sidebar: Show it in the sidebar.
            allow_single_word: Permit a url_path without a hyphen.
        """
        fields = _drop_none(icon=icon)
        if allow_single_word:
            fields["allow_single_word"] = True
        return await ws.ws_command(
            "lovelace/dashboards/create",
            url_path=url_path,
            title=title,
            require_admin=require_admin,
            show_in_sidebar=show_in_sidebar,
            **fields,
        )

    @mcp.tool(annotations=mutation("Update Dashboard", idempotent=True))
    async def update_dashboard(
        dashboard_id: str,
        title: str | None = None,
        icon: str | None = None,
        require_admin: bool | None = None,
        show_in_sidebar: bool | None = None,
    ) -> dict:
        """Update a storage-mode dashboard's metadata (not its content).

        Args:
            dashboard_id: The dashboard's id from list_dashboards. This is a
                slug (e.g. 'garden_view'), not the url_path ('garden-view').
            title: New sidebar title.
            icon: New MDI icon.
            require_admin: Only admins can open it.
            show_in_sidebar: Show it in the sidebar.
        """
        fields = _drop_none(
            title=title, icon=icon, require_admin=require_admin,
            show_in_sidebar=show_in_sidebar,
        )
        return await ws.ws_command(
            "lovelace/dashboards/update", dashboard_id=dashboard_id, **fields
        )

    @mcp.tool(
        annotations=mutation("Delete Dashboard", destructive=True, idempotent=True)
    )
    async def delete_dashboard(dashboard_id: str, confirm: bool = False) -> dict:
        """Delete a storage-mode dashboard and its stored config.

        Args:
            dashboard_id: The dashboard's id from list_dashboards. This is a
                slug (e.g. 'garden_view'), not the url_path ('garden-view').
            confirm: Must be true to perform this destructive operation.
        """
        if not confirm:
            raise HAToolError(
                "confirmation_required",
                f"set confirm=true to delete dashboard {dashboard_id}",
            )
        await ws.ws_command("lovelace/dashboards/delete", dashboard_id=dashboard_id)
        return {"deleted": True, "dashboard_id": dashboard_id}

    # -- whole config ---------------------------------------------------------

    @mcp.tool(annotations=mutation("Save Dashboard Config", idempotent=True))
    async def save_dashboard_config(config: dict, url_path: str | None = None) -> dict:
        """Replace a dashboard's entire config. Returns the config read back.

        Use this to take control of an auto-generated default dashboard or to
        rewrite a dashboard wholesale. For smaller edits prefer
        set_dashboard_view / set_dashboard_card.

        Args:
            config: Full dashboard config, e.g. {"title": "Home", "views":
                [{"title": "Main", "path": "main", "cards": [...]}]}. Must
                contain a 'views' list.
            url_path: Dashboard url_path, or None for the default dashboard.
        """
        _validate_config(config)
        return await _save(ws, url_path, config)

    @mcp.tool(
        annotations=mutation(
            "Delete Dashboard Config", destructive=True, idempotent=True
        )
    )
    async def delete_dashboard_config(
        url_path: str | None = None, confirm: bool = False
    ) -> dict:
        """Delete a dashboard's stored config, leaving the dashboard itself.

        The default dashboard reverts to auto-generated; a custom dashboard
        becomes empty.

        Args:
            url_path: Dashboard url_path, or None for the default dashboard.
            confirm: Must be true to perform this destructive operation.
        """
        if not confirm:
            raise HAToolError(
                "confirmation_required",
                f"set confirm=true to delete the config of dashboard {url_path!r}",
            )
        await ws.ws_command("lovelace/config/delete", url_path=url_path)
        return {"deleted": True, "url_path": url_path}

    # -- views ----------------------------------------------------------------

    @mcp.tool(annotations=mutation("Set Dashboard View", idempotent=True))
    async def set_dashboard_view(
        view: dict,
        url_path: str | None = None,
        view_ref: int | str | None = None,
        position: int | None = None,
    ) -> dict:
        """Add or replace one view in a dashboard. Returns {index, view}.

        With view_ref omitted the view is inserted at position (appended when
        position is also omitted). With view_ref given, that view is replaced.

        Args:
            view: The view config, e.g. {"title": "Garden", "path": "garden",
                "cards": [...]} or {"title": ..., "type": "sections",
                "sections": [{"type": "grid", "cards": [...]}]}.
            url_path: Dashboard url_path, or None for the default dashboard.
            view_ref: Existing view to replace: an integer index or the view's
                'path' string.
            position: Insertion index when adding (ignored when replacing).
        """
        config = await _load(ws, url_path)
        views = config["views"]
        if view_ref is None:
            index = len(views) if position is None else position
            if not 0 <= index <= len(views):
                raise HAToolError(
                    "position_out_of_range",
                    f"position {index} out of range for {len(views)} views",
                )
            views.insert(index, view)
        else:
            index, _ = _resolve_view(config, view_ref)
            views[index] = view
        saved = await _save(ws, url_path, config)
        return {"index": index, "view": saved["views"][index]}

    @mcp.tool(
        annotations=mutation("Delete Dashboard View", destructive=True, idempotent=True)
    )
    async def delete_dashboard_view(
        view_ref: int | str, url_path: str | None = None, confirm: bool = False
    ) -> list[dict]:
        """Delete one view from a dashboard. Returns the remaining views' summary.

        Args:
            view_ref: The view to delete: an integer index or its 'path' string.
            url_path: Dashboard url_path, or None for the default dashboard.
            confirm: Must be true to perform this destructive operation.
        """
        if not confirm:
            raise HAToolError(
                "confirmation_required",
                f"set confirm=true to delete view {view_ref!r} from dashboard {url_path!r}",
            )
        config = await _load(ws, url_path)
        index, _ = _resolve_view(config, view_ref)
        del config["views"][index]
        saved = await _save(ws, url_path, config)
        return _summarize_views(saved)

    # -- cards ----------------------------------------------------------------

    @mcp.tool(annotations=mutation("Set Dashboard Card", idempotent=True))
    async def set_dashboard_card(
        card: dict,
        view_ref: int | str,
        url_path: str | None = None,
        section: int | None = None,
        card_index: int | None = None,
    ) -> dict:
        """Add or replace one card in a view. Returns {view, section, index, card}.

        With card_index omitted the card is appended; otherwise the card at that
        index is replaced.

        Args:
            card: The card config, e.g. {"type": "entities", "entities":
                ["light.kitchen"]}.
            view_ref: Target view: an integer index or its 'path' string.
            url_path: Dashboard url_path, or None for the default dashboard.
            section: Section index. Required for views of type 'sections';
                must be omitted for other view types.
            card_index: Existing card index to replace.
        """
        config = await _load(ws, url_path)
        view_index, view = _resolve_view(config, view_ref)
        cards = _card_list(view, section)
        if card_index is None:
            index = len(cards)
            cards.append(card)
        else:
            _check_index(cards, card_index, "card")
            index = card_index
            cards[index] = card
        saved = await _save(ws, url_path, config)
        saved_view = saved["views"][view_index]
        return {
            "view": view_index,
            "section": section,
            "index": index,
            "card": _card_list(saved_view, section)[index],
        }

    @mcp.tool(
        annotations=mutation("Delete Dashboard Card", destructive=True, idempotent=True)
    )
    async def delete_dashboard_card(
        view_ref: int | str,
        card_index: int,
        url_path: str | None = None,
        section: int | None = None,
        confirm: bool = False,
    ) -> dict:
        """Delete one card from a view. Returns {view, section, remaining_cards}.

        Args:
            view_ref: Target view: an integer index or its 'path' string.
            card_index: Index of the card to delete.
            url_path: Dashboard url_path, or None for the default dashboard.
            section: Section index. Required for views of type 'sections';
                must be omitted for other view types.
            confirm: Must be true to perform this destructive operation.
        """
        if not confirm:
            raise HAToolError(
                "confirmation_required",
                f"set confirm=true to delete card {card_index} from view {view_ref!r}",
            )
        config = await _load(ws, url_path)
        view_index, view = _resolve_view(config, view_ref)
        cards = _card_list(view, section)
        _check_index(cards, card_index, "card")
        del cards[card_index]
        saved = await _save(ws, url_path, config)
        remaining = _card_list(saved["views"][view_index], section)
        return {"view": view_index, "section": section, "remaining_cards": len(remaining)}

    # -- resources ------------------------------------------------------------

    @mcp.tool(annotations=mutation("Create Dashboard Resource"))
    async def create_dashboard_resource(res_type: str, url: str) -> dict:
        """Register a Lovelace resource (custom card). Returns it including id.

        Args:
            res_type: One of 'module' (ES module, the usual choice for custom
                cards), 'js', 'css', or 'html'.
            url: Resource URL, e.g. '/local/my-card.js' or '/hacsfiles/...'.
        """
        _validate_res_type(res_type)
        return await ws.ws_command("lovelace/resources/create", res_type=res_type, url=url)

    @mcp.tool(annotations=mutation("Update Dashboard Resource", idempotent=True))
    async def update_dashboard_resource(
        resource_id: str, res_type: str | None = None, url: str | None = None
    ) -> dict:
        """Update a Lovelace resource's type or URL.

        Args:
            resource_id: The resource id from list_dashboard_resources.
            res_type: New type ('module', 'js', 'css', or 'html').
            url: New URL.
        """
        if res_type is not None:
            _validate_res_type(res_type)
        fields = _drop_none(res_type=res_type, url=url)
        return await ws.ws_command(
            "lovelace/resources/update", resource_id=resource_id, **fields
        )

    @mcp.tool(
        annotations=mutation(
            "Delete Dashboard Resource", destructive=True, idempotent=True
        )
    )
    async def delete_dashboard_resource(resource_id: str, confirm: bool = False) -> dict:
        """Remove a Lovelace resource. Cards that depend on it stop rendering.

        Args:
            resource_id: The resource id from list_dashboard_resources.
            confirm: Must be true to perform this destructive operation.
        """
        if not confirm:
            raise HAToolError(
                "confirmation_required",
                f"set confirm=true to delete resource {resource_id}",
            )
        await ws.ws_command("lovelace/resources/delete", resource_id=resource_id)
        return {"deleted": True, "resource_id": resource_id}


# -- helpers --------------------------------------------------------------------


def _drop_none(**kwargs):
    """Return only the keyword arguments that are not None."""
    return {k: v for k, v in kwargs.items() if v is not None}


def _validate_config(config: Any) -> None:
    if not isinstance(config, dict) or not isinstance(config.get("views"), list):
        raise HAToolError("invalid_config", "config must be an object with a 'views' list")


def _validate_res_type(res_type: str) -> None:
    if res_type not in _RESOURCE_TYPES:
        raise HAToolError(
            "invalid_resource_type",
            f"res_type must be one of {list(_RESOURCE_TYPES)}, got {res_type!r}",
        )


async def _load(ws: HAWebSocketClient, url_path: str | None) -> dict:
    """Fetch the current stored config (bypassing cache) and validate its shape."""
    config = await ws.ws_command("lovelace/config", url_path=url_path, force=True)
    _validate_config(config)
    return config


async def _save(ws: HAWebSocketClient, url_path: str | None, config: dict) -> dict:
    """Save a config, then read it back so callers see what was stored."""
    await ws.ws_command("lovelace/config/save", url_path=url_path, config=config)
    return await ws.ws_command("lovelace/config", url_path=url_path, force=True)


def _check_index(seq: list, index: int, what: str) -> None:
    if not 0 <= index < len(seq):
        raise HAToolError(
            f"{what}_not_found", f"{what} index {index} out of range for {len(seq)} {what}s"
        )


def _resolve_view(config: dict, view_ref: int | str) -> tuple[int, dict]:
    """Locate a view by integer index or by its 'path'."""
    views = config["views"]
    if isinstance(view_ref, int):
        _check_index(views, view_ref, "view")
        return view_ref, views[view_ref]
    for i, view in enumerate(views):
        if view.get("path") == view_ref:
            return i, view
    paths = [v.get("path") for v in views]
    raise HAToolError(
        "view_not_found", f"no view with path {view_ref!r}; available paths: {paths}"
    )


def _card_list(view: dict, section: int | None) -> list:
    """Return the mutable card list for a view (or one of its sections)."""
    if view.get("type") == "sections":
        if section is None:
            raise HAToolError(
                "section_required", "this view uses sections; pass section=<index>"
            )
        sections = view.setdefault("sections", [])
        _check_index(sections, section, "section")
        return sections[section].setdefault("cards", [])
    if section is not None:
        raise HAToolError(
            "section_not_applicable", "this view does not use sections; omit section"
        )
    return view.setdefault("cards", [])


def _summarize_views(config: dict) -> list[dict]:
    return [
        {"index": i, "title": v.get("title"), "path": v.get("path")}
        for i, v in enumerate(config.get("views", []))
    ]
